import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourceRoot = path.join(projectRoot, "src");
const scriptManifestPath = path.join(
  sourceRoot,
  "js/main/renderer-scripts.json",
);
const bundleManifestPaths = {
  core: scriptManifestPath,
  agent: path.join(sourceRoot, "js/main/renderer-agent-scripts.json"),
  markdown: path.join(sourceRoot, "js/main/renderer-markdown-scripts.json"),
};
const workerSourcePath = path.join(
  sourceRoot,
  "js/worker/highlight.worker.js",
);
const runtimeAssets = [
  ["assets/icons/close.svg", path.join(sourceRoot, "assets/icons/close.svg")],
  [
    "assets/logo/NCE/dark-logo.png",
    path.join(sourceRoot, "assets/logo/NCE/dark-logo.png"),
  ],
];

async function rendererScriptPaths(bundle = "core") {
  const manifestPath = bundleManifestPaths[bundle];
  if (!manifestPath) throw new Error(`Unknown renderer bundle: ${bundle}`);
  const paths = JSON.parse(await fs.readFile(manifestPath, "utf8"));
  if (!Array.isArray(paths) || paths.some((file) => typeof file !== "string")) {
    throw new Error(`${bundle} renderer manifest must contain an ordered path list`);
  }
  return paths;
}

export async function buildRendererScript(bundle = "core") {
  const paths = await rendererScriptPaths(bundle);
  const chunks = [];

  for (const file of paths) {
    const sourcePath = path.resolve(sourceRoot, file);
    const relativePath = path.relative(sourceRoot, sourcePath);
    if (
      relativePath === ".." ||
      relativePath.startsWith(`..${path.sep}`) ||
      path.isAbsolute(relativePath)
    ) {
      throw new Error(`Renderer script escapes src/: ${file}`);
    }

    const source = await fs.readFile(sourcePath, "utf8");
    chunks.push(`;\n/* ${file.replaceAll("*/", "* /")} */\n${source}\n`);
  }

  return `/* Generated by Vite from renderer-${bundle}-scripts.json. */\n${chunks.join(";")};\n`;
}

export function rendererEntrypointPlugin() {
  const reloadPaths = new Set([...Object.values(bundleManifestPaths), workerSourcePath]);

  return {
    name: "nce-classic-renderer-entrypoint",

    async configureServer(server) {
      const manifestAndWorker = [...Object.values(bundleManifestPaths), workerSourcePath];
      server.watcher.add(manifestAndWorker);
      const bundlePaths = await Promise.all(
        Object.keys(bundleManifestPaths).map(async (bundle) => rendererScriptPaths(bundle)),
      );
      const rendererSources = bundlePaths.flat().map((file) => path.resolve(sourceRoot, file));
      for (const sourcePath of rendererSources) reloadPaths.add(sourcePath);
      server.watcher.add(rendererSources);

      server.middlewares.use((request, response, next) => {
        const pathname = new URL(
          request.url || "/",
          "http://nce.local",
        ).pathname;
        const bundles = {
          "/html/renderer.js": "core",
          "/html/agent.js": "agent",
          "/html/markdown.js": "markdown",
        };
        const bundle = bundles[pathname];
        if (!bundle) return next();

        void buildRendererScript(bundle).then(
          (source) => {
            response.statusCode = 200;
            response.setHeader("Content-Type", "text/javascript; charset=utf-8");
            response.setHeader("Cache-Control", "no-store");
            response.end(source);
          },
          next,
        );
      });

      server.watcher.on("change", (changedPath) => {
        if (reloadPaths.has(path.resolve(changedPath))) {
          server.ws.send({ type: "full-reload" });
        }
      });

    },

    async generateBundle() {
      for (const [bundle, fileName] of [
        ["core", "html/renderer.js"],
        ["agent", "html/agent.js"],
        ["markdown", "html/markdown.js"],
      ]) {
        this.emitFile({
          type: "asset",
          fileName,
          source: await buildRendererScript(bundle),
        });
      }
      this.emitFile({
        type: "asset",
        fileName: "js/worker/highlight.worker.js",
        source: await fs.readFile(workerSourcePath),
      });
      for (const [fileName, sourcePath] of runtimeAssets) {
        this.emitFile({
          type: "asset",
          fileName,
          source: await fs.readFile(sourcePath),
        });
      }
    },
  };
}
